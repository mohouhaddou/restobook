import fs from 'node:fs';

function read(file) {
  return fs.readFileSync(file, 'utf8');
}

function write(file, source) {
  fs.writeFileSync(file, source);
}

function replaceAll(file, replacements) {
  let source = read(file);
  for (const [from, to] of replacements) {
    if (!source.includes(from)) {
      console.warn(`missing fragment in ${file}: ${from.slice(0, 90).replace(/\n/g, ' ')}`);
      continue;
    }
    source = source.split(from).join(to);
  }
  write(file, source);
}

function mergeJson(file, additions) {
  const current = fs.existsSync(file) ? JSON.parse(read(file)) : {};
  write(file, `${JSON.stringify({ ...current, ...additions }, null, 2)}\n`);
}

