import fs from 'node:fs';
import path from 'node:path';

function replaceInFile(file, replacements) {
  const abs = path.resolve(file);
  let source = fs.readFileSync(abs, 'utf8');
  let changed = false;
  for (const [from, to] of replacements) {
    if (!source.includes(from)) {
      console.warn(`missing fragment in ${file}: ${from.slice(0, 80)}`);
      continue;
    }
    source = source.split(from).join(to);
    changed = true;
  }
  if (changed) fs.writeFileSync(abs, source);
}

function mergeJson(file, additions) {
  const abs = path.resolve(file);
  const current = JSON.parse(fs.readFileSync(abs, 'utf8'));
  const next = { ...current, ...additions };
  fs.writeFileSync(abs, `${JSON.stringify(next, null, 2)}\n`);
}

